import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js';
import { HTMLHandler } from 'mathjax-full/js/handlers/html/HTMLHandler.js';
import { SVG } from 'mathjax-full/js/output/svg.js';
import { generate, parse, walk } from 'css-tree';
import { normalizeNamedColors } from '../src/themes/named-colors.mjs';

const root = new URL('../', import.meta.url);

/** The SVG jax enumerates every registered wrapper and font style, independent of a sample formula. */
export function mathSvgCss() {
	const adaptor = liteAdaptor();
	const svg = new SVG({ fontCache: 'none' });
	const document = new HTMLHandler(adaptor).create('', { OutputJax: svg });
	const css = parse(adaptor.textContent(svg.styleSheet(document)));
	walk(css, { visit: 'Declaration', enter(node) { normalizeNamedColors(node.property, node.value); } });
	walk(css, { visit: 'SelectorList', enter(list) {
		list.children.forEach(selector => {
			const text = generate(selector);
			const scoped = text.startsWith('mjx-container')
				? text.replace('mjx-container', '.paraflow-svg-math')
				: text.startsWith('[jax=') ? '.paraflow-svg-math' + text : '.paraflow-svg-math ' + text;
			selector.children = parse(scoped, { context: 'selector' }).children;
		});
	} });
	return generate(css);
}

export async function pluginStyles() {
	// This entry imports only pure CSS strings/functions, never the Obsidian or editor runtime.
	const bundled = await build({
		absWorkingDir: fileURLToPath(root), entryPoints: ['src/display/styles.ts'],
		bundle: true, platform: 'node', format: 'esm', write: false,
	});
	// eslint-disable-next-line no-unsanitized/method -- Executes only esbuild output from the fixed local CSS-only entry above.
	const { enhancementCss } = await import('data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64'));
	const base = await readFile(new URL('src/display/base.css', root), 'utf8');
	return [
		'/* Generated by build/styles.mjs. Edit src/display/base.css or the module-owned CSS sources. */',
		base, enhancementCss, mathSvgCss(),
	].join('\n').replaceAll('\r\n', '\n');
}

export async function writePluginStyles() {
	const target = new URL('styles.css', root);
	const css = await pluginStyles();
	if (await readFile(target, 'utf8') !== css) await writeFile(target, css);
}

/** An empty injected module gives esbuild's watcher ownership of the CSS-only graph. */
export function pluginStylesPlugin() {
	return { name: 'plugin-styles', setup(plugin) {
		plugin.initialOptions.inject = [...(plugin.initialOptions.inject ?? []), 'paraflow:styles'];
		plugin.onStart(writePluginStyles);
		plugin.onResolve({ filter: /^paraflow:styles$/ }, () => ({ path: 'styles', namespace: 'paraflow-styles' }));
		plugin.onLoad({ filter: /.*/, namespace: 'paraflow-styles' }, async () => {
			const graph = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['src/display/styles.ts'], bundle: true, platform: 'node', write: false, metafile: true });
			return { contents: '', loader: 'js', watchFiles: [
				fileURLToPath(new URL('src/display/base.css', root)),
				...Object.keys(graph.metafile.inputs).map(path => fileURLToPath(new URL(path, root))),
			] };
		});
	} };
}
