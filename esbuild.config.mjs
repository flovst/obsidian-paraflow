import { readFileSync } from 'node:fs';
import { loadThemeBundles } from './build/theme-bundles.mjs';
import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { pluginStylesPlugin } from './build/styles.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

${readFileSync('THIRD-PARTY-NOTICES.txt', 'utf8')}
*/
`;

const prod = process.argv[2] === 'production';

const bundledThemes = loadThemeBundles();

const context = await esbuild.context({
	plugins: [pluginStylesPlugin()],
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	define: {
		__PARAFLOW_CLASSIC_CSS__: JSON.stringify(readFileSync('themes/builtin-classic/theme.css', 'utf8')),
		__PARAFLOW_BUNDLED_THEMES__: JSON.stringify(bundledThemes),
	},
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
